export type Lang = "en" | "ja";
export const DICTS: Record<Lang, Record<string, string>> = { en, ja };
export type Vars = Record<string, string | number>;
export type TFn = (key: Key, vars?: Vars) => string;

export function translate(lang: Lang, key: string, vars?: Vars): string {
  const s = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFn;
  has: (key: string) => boolean;
  /** Translate a server enum value; unknown values are shown humanised, never hidden. */
  tv: (group: string, value: string) => string;
  fmtDate: (iso: string) => string;
  fmtNum: (n: number) => string;
}

const Ctx = createContext<I18n | null>(null);

function detect(): Lang {
  return typeof navigator !== "undefined" && navigator.language?.startsWith("ja") ? "ja" : "en";
}

export function I18nProvider({ children, initial }: { children: ReactNode; initial?: Lang }) {
  const [lang, setLang] = useState<Lang>(initial ?? detect);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const t = useCallback<TFn>((k, v) => translate(lang, k, v), [lang]);
  const value = useMemo<I18n>(() => {
    const locale = lang === "ja" ? "ja-JP" : "en-GB";
    const dt = new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short" });
    const nf = new Intl.NumberFormat(locale);
    return {
      lang,
      setLang,
      t,
      has: (k) => k in DICTS[lang],
      tv: (g, v) => DICTS[lang][`${g}.${v}`] ?? v.replaceAll("_", " "),
      fmtDate: (iso) => {
        const d = new Date(iso);
        return Number.isNaN(d.getTime()) ? iso : dt.format(d);
      },
      fmtNum: (n) => nf.format(n),
    };
  }, [lang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const c = useContext(Ctx);
  if (!c) throw new Error("I18nProvider missing");
  return c;
}
